"""How well does the heating model (heating.py) predict head readings it did not see?

    python adapters/cotton_candy/validate_heating.py ../datasets/cotton-candy/processed

Writes adapters/cotton_candy/heating_report.md. Three checks on the real runs:
  1. in-sample fit per phase;
  2. forecasting: fit on the first half of a phase, predict the second half from the last reading used, against
     simple alternatives (no change, a straight line, the batch's pooled curve, and, for spinning, the run's own
     waiting curve: what replaying the real signal across a counterfactual start amounts to);
  3. the whole spinning phase predicted from the real head at the start with batch parameters estimated
     WITHOUT the run (leave one out), by start temperature: does the model hold when the start moves?
"""
import os
import sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))
from adapters import get_adapter  # noqa: E402
from adapters.cotton_candy.heating import (fit_heating, fit_phase, newton, phase_readings, _pooled,  # noqa: E402
                                           batch_slope, MIN_READINGS)

HORIZONS = [10, 20, 40]


def errors(tau, err):
    """RMSE overall and |error| near each horizon (the reading closest to it, within 3 s), bias overall."""
    out = {"rmse": float(np.sqrt(np.mean(err ** 2))), "bias": float(np.mean(err))}
    for h in HORIZONS:
        j = np.argmin(np.abs(tau - h))
        out[f"abs@{h}s"] = float(abs(err[j])) if abs(tau[j] - h) <= 3 else np.nan
    return out


def forecast(cases, fits, phase):
    rows = []
    for c in cases:
        x, y = phase_readings(c, phase)
        if len(x) < 2 * MIN_READINGS or x[-1] < 40:
            continue
        cut = x[-1] / 2
        tr, te = x <= cut, x > cut
        own = fit_phase(x[tr], y[tr])
        if own is None:
            continue
        x0, y0 = x[tr][-1], y[tr][-1]
        tau = x[te] - x0
        others = [o for o in cases if o.group == c.group and o.case_id != c.case_id]
        pooled = _pooled(others, phase) or _pooled([o for o in cases if o.case_id != c.case_id], phase)
        line = np.polyfit(x[tr], y[tr], 1)
        preds = {
            "Newton, own first half": newton(tau, own[0], own[1], y0),
            "Newton, batch (without run)": newton(tau, pooled[0], pooled[1], y0),
            "straight line, own first half": y0 + line[0] * tau,
            "no change": np.full_like(tau, y0),
        }
        if phase == "wait":
            s = batch_slope(others) or batch_slope([o for o in cases if o.case_id != c.case_id])
            preds["straight line, batch median slope (without run)"] = y0 + s * tau
        if phase == "spin":
            preds["run's WAITING line (replay)"] = y0 + fits[c.case_id].wait.slope * tau
        for name, p in preds.items():
            rows.append(dict(case=c.case_id, method=name, **errors(tau, p - y[te])))
    return pd.DataFrame(rows)


def leave_one_out_spin(cases):
    rows = []
    for c in cases:
        x, y = phase_readings(c, "spin")
        if len(x) < MIN_READINGS:
            continue
        others = [o for o in cases if o.group == c.group and o.case_id != c.case_id]
        p = _pooled(others, "spin") or _pooled([o for o in cases if o.case_id != c.case_id], "spin")
        err = newton(x, p[0], p[1], y[0]) - y
        rows.append(dict(case=c.case_id, head_start=y[0], **errors(x, err)))
    return pd.DataFrame(rows)


def table(df, cols):
    g = df.groupby("method")[cols].median().sort_values("rmse")
    n = df.groupby("method").size()
    lines = ["| Method | runs | " + " | ".join(f"median {k}" for k in cols) + " |", "|---" * (len(cols) + 2) + "|"]
    for m, r in g.iterrows():
        lines.append(f"| {m} | {n[m]} | " + " | ".join(f"{v:+.2f}" if k == "bias" else f"{v:.2f}"
                                                         for k, v in r.items()) + " |")
    return lines


def main():
    data = sys.argv[1]
    A = get_adapter("cotton_candy")
    cases = A.load(data, verbose=False)
    fits = fit_heating(cases)
    out = ["# Heating model: validation on held-out readings", "",
           f"{len(cases)} real runs. Errors in C. Generated by `validate_heating.py`.", "",
           "Chosen model (heating.py): waiting = the run's own straight line (else its batch's median slope); "
           "spinning = the Newton curve pooled over the run's batch. Sections 2 and 3 show why.", "",
           "## 1. In-sample fit of the chosen model", "",
           "| Phase | model | params from run | from batch | from all runs | median R^2 | median RMSE | "
           "parameters p10 / p50 / p90 |", "|---" * 8 + "|"]
    for ph in ["wait", "spin"]:
        pf = [getattr(fits[c.case_id], ph) for c in cases]
        cnt = {s: sum(p.source == s for p in pf) for s in ["run", "batch", "all"]}
        q = lambda v, d: " / ".join(f"{x:.{d}f}" for x in np.nanpercentile(v, [10, 50, 90]))
        params = (f"slope {q([p.slope for p in pf], 3)} C/s" if ph == "wait" else
                  f"T_inf {q([p.t_inf for p in pf], 0)} C, k {q([p.k for p in pf], 4)} 1/s")
        out.append(f"| {ph} | {pf[0].kind} | {cnt['run']} | {cnt['batch']} | {cnt['all']} | "
                   f"{np.nanmedian([p.r2 for p in pf]):.3f} | {np.nanmedian([p.rmse for p in pf]):.2f} | {params} |")
    cols = ["rmse", "bias"] + [f"abs@{h}s" for h in HORIZONS]
    for ph, title in [("wait", "waiting"), ("spin", "spinning")]:
        f = forecast(cases, fits, ph)
        out += ["", f"## 2. Forecasting the second half of the {title} phase", "",
                "Fit on the first half, predict the rest from the last reading used. Median over runs; "
                "bias = mean (predicted - real).", ""] + table(f, cols)
    loo = leave_one_out_spin(cases)
    out += ["", "## 3. Whole spinning phase from the real head at the start, batch parameters without the run", "",
            "| Head at start | runs | median RMSE | median bias | median abs@40s |", "|---|---|---|---|---|"]
    for band, g in loo.groupby(pd.cut(loo.head_start, [0, 55, 60, 65, 70, 75, 80, 100]), observed=True):
        out.append(f"| {band} | {len(g)} | {g.rmse.median():.2f} | {g.bias.median():+.2f} | "
                   f"{g['abs@40s'].median():.2f} |")
    path = os.path.join(HERE, "heating_report.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))
    print(f"\nwritten to {path}")


if __name__ == "__main__":
    main()
